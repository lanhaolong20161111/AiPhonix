/**
 * 数学页共用的矢量简笔画图标。
 *
 * ★★ 这是图标的**唯一来源**。Android 端由 `web/_gen_math_icons.ts` 从本文件生成
 *    `app/src/main/java/com/example/ai/ui/icon/MathIcons.kt`。
 *    改图标只改这里 → 重跑 `./web/node_modules/.bin/tsx web/_gen_math_icons.ts` → 两端同步。
 *    **不要手工去改 .kt**（会被覆盖）。
 *
 * 坐标系统一用 0..100 的正方形 viewBox，两端渲染时按目标尺寸等比缩放。
 *
 * 图元用「紧凑数组」而不是 SVG path 的 d 字符串：
 * 简笔画只需要 圆 / 矩形 / 圆角矩形 / 线段 / 多边形 五种，两端都能用原生 API 直接画
 * （web 用 <circle>/<rect>/<line>/<polygon>，Compose 用 drawCircle/drawRoundRect/drawLine/drawPath），
 * 省掉在 Android 侧再写一个 SVG path 解析器。
 *
 *   ["c",  cx, cy, r,            mode?]   圆
 *   ["r",  x, y, w, h,           mode?]   矩形
 *   ["rr", x, y, w, h, rad,      mode?]   圆角矩形
 *   ["l",  x1, y1, x2, y2, w?]            线段（w 省略时取 DEFAULT_LINE_W）
 *   ["p",  [x1,y1,x2,y2,...], closed, mode?] 多边形 / 折线（closed 决定是否闭合）
 *
 * `mode` 只有一个取值 `"o"`（outline）：**只描边、不填充**。
 * 需要「挖空」时用它 —— 比如把指甲盖从手指里挖出来、把车窗从车身里挖出来。
 * 约定：mode 永远是数组的**最后一个**元素，且是字符串（数字图元不会与它混淆）。
 */
export type MathPrim =
  | ["c", number, number, number, ("o")?]
  | ["r", number, number, number, number, ("o")?]
  | ["rr", number, number, number, number, number, ("o")?]
  | ["l", number, number, number, number, number?]
  | ["p", number[], boolean, ("o")?]

export const DEFAULT_LINE_W = 3

/** 图元是否「只描边不填充」。见本文件顶部 mode 说明。 */
export function isOutline(p: MathPrim): boolean {
  const arr = p as unknown as unknown[]
  return arr[arr.length - 1] === "o"
}

/**
 * 图标配色档位。两端各自映射到自己的色板，图标数据里不写死颜色。
 *  - `soft`  淡填充 + 深描边，绝大多数参照物物品用这档
 *  - `ink`   实心深色，用于「人」这类主体剪影，跟淡色物品拉开层次
 *  - `accent` 强调色，用于「本页在讲的那个东西」（如当前单位的真实尺寸条）
 */
export type MathIconTone = "soft" | "ink" | "accent"

export interface MathIconSpec {
  prims: MathPrim[]
  /** 缺省 soft */
  tone?: MathIconTone
}

