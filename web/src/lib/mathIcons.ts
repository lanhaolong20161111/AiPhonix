/** 取图标；名字打错时返回 undefined（两端渲染件都会退化成不画，而不是崩） */
export function mathIcon(name: string): MathIconSpec | undefined {
  return MATH_ICONS[name]
}

/** 单元测试用：所有图标名 */
export function mathIconNames(): string[] {
  return Object.keys(MATH_ICONS)
}
