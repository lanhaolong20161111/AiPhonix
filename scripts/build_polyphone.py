# 合并已知 + 词库匹配（取 union）
result = {}
for ch, readings in KNOWN_POLYPHONES.items():
    # 从词库获取已有词语
    wds = char_to_words.get(ch, [])
    existing_words = {w['word'] for w in wds}
    
    readings_data = {}
    for py, words_list in readings:
        # 合并来自已知列表的词和来自词库的词
        all_words = []
        for w in words_list:
            if w not in all_words:
                all_words.append(w)
        # 加上词库中匹配该读音的词
        for w in wds:
            full_py = w['full_pinyin'].split()
            char_idx = w['word'].index(ch)
            if char_idx < len(full_py) and full_py[char_idx].rstrip('012345') == py.rstrip('012345'):
                if w['word'] not in all_words:
                    all_words.append(w['word'])
        
        if all_words:
            readings_data[py] = all_words[:5]  # 最多5个词
    
    primary = max(readings_data.keys(), key=lambda k: len(readings_data[k])) if readings_data else ''
    
    if len(readings_data) >= 1:
        result[ch] = {
            'pronunciations': sorted(readings_data.keys()),
            'words': dict(readings_data),
            'primary': primary
        }

print(f'确认的多音字: {len(result)} 个')

