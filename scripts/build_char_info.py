    result = []
    ok_rad = ok_str = ok_dec = 0
    
    for c in sorted(all_chars):
        # 偏旁
        radical = rad.trans_str(c) or ""
        if radical:
            ok_rad += 1
        if not radical:
            radical = "其他"
        
        # 拆字
        comps = chaizi.query(c)
        if comps:
            ok_dec += 1
        else:
            comps = []
        
        # 结构
        structure = get_structure(c, radical, comps)
        if structure:
            ok_str += 1
        
        # 笔画
        strokes = STROKE_MAP.get(c, 0)
        
        # 组词
        words = extract_words(c, wordbank)
        
        result.append({
            "char": c,
            "radical": radical,
            "decomposition": comps,
            "stroke_count": strokes,
            "structure": structure,
            "words": words,
        })
    
    print(f"偏旁: {ok_rad}/{len(all_chars)}")
