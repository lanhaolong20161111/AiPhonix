def extract_words(char, wordbank):
    """从词表中取包含该字的词语"""
    words = set()
    for entry in wordbank.get("words", []):
        text = entry.get("text", "")
        if char in text:
            words.add(text)
    return sorted(words, key=lambda w: len(w))[:8]

def load_wordbank():
    with open(WORD_BANK, "r", encoding="utf-8") as f:
        return json.load(f)

def main():
    wordbank = load_wordbank()
    chars = wordbank.get("chars", [])
    all_chars = set()
    for e in chars:
        t = e.get("text", "")
        if len(t) == 1:
            all_chars.add(t)
    
